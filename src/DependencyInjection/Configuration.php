                    ->children()
                        ->scalarNode('directory_mode')
                            ->defaultValue('0775')
                            ->validate()
                                ->ifTrue(static fn (mixed $value): bool => !is_string($value) || preg_match('/^0?[0-3]?[0-7]{3}$/D', $value) !== 1)
                                ->thenInvalid('SoFinder directory_mode must be a quoted octal mode such as "0775" or "2775".')
                            ->end()
