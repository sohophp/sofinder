                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('mode')->values(['auto', 'manager', 'picker'])->defaultValue('auto')->end()
                        ->booleanNode('header')->defaultTrue()->end()
                        ->booleanNode('logo')->defaultTrue()->end()
                        ->booleanNode('search')->defaultTrue()->end()
                        ->booleanNode('language_switcher')->defaultTrue()->end()
                        ->booleanNode('view_switcher')->defaultTrue()->end()
                        ->booleanNode('folder_tree')->defaultFalse()->end()
                        ->enumNode('scale')->values(['compact', 'standard', 'large', 'xlarge'])->defaultValue('standard')->end()
