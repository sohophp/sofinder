                    ->end()
                ->end()
                ->arrayNode('features')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('folder_tree')->defaultTrue()->end()
                        ->booleanNode('recent')->defaultTrue()->end()
                        ->booleanNode('favorites')->defaultTrue()->end()
