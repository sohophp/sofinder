                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultFalse()->end()
                        ->scalarNode('endpoint')
                            ->defaultValue('tcp://127.0.0.1:3310')
                            ->validate()
                                ->ifTrue(static fn (mixed $value): bool => !is_string($value) || preg_match('#^(?:tcp://[A-Za-z0-9.:-]+|unix:///[^\x00-\x1F]+)$#D', $value) !== 1)
                                ->thenInvalid('SoFinder malware_scanning.endpoint must be a tcp:// host or absolute unix:/// socket.')
                            ->end()
                        ->end()
                        ->floatNode('timeout_seconds')->min(0.1)->max(60)->defaultValue(5.0)->end()
                        ->integerNode('history_limit')->min(1)->max(1000)->defaultValue(100)->end()
                        ->arrayNode('status_roles')->scalarPrototype()->end()->defaultValue(['ROLE_ADMIN'])->end()
                    ->end()
                ->end()
                ->arrayNode('image_processing')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('driver')->values(['auto', 'gd', 'imagick'])->defaultValue('auto')->end()
                        ->integerNode('max_width')->min(1)->max(100000)->defaultValue(12000)->end()
